"""Generate coverage from pinned official Discovery, without granting access."""
import argparse
import hashlib
import json
from pathlib import Path

from google_utils_mcp.registry import IMPLEMENTED, VERSIONS, catalog, discovery


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = ["# API coverage", "", "Generated by `uv run python scripts/generate_api_catalog.py`.",
             "Implemented means wrapper and offline validation, not universal live-account coverage.", "",
             "| Method | Status | Scopes |", "| --- | --- | --- |"]
    manifest = json.loads(Path("discovery/manifest.json").read_text())
    for api, version in VERSIONS.items():
        data = Path(f"src/google_utils_mcp/discovery/{api}.{version}.json").read_bytes()
        assert hashlib.sha256(data).hexdigest() == manifest[f"{api}.{version}"]["sha256"]
        assert discovery(api)["revision"] == manifest[f"{api}.{version}"]["revision"]
        for method_id, method in sorted(catalog(api).items()):
            status = "implemented" if method_id in IMPLEMENTED else "deferred (not exposed)"
            scopes = ", ".join(s.rsplit("/", 1)[-1] for s in method.get("scopes", []))
            lines.append(f"| `{method_id}` | {status} | {scopes} |")
    content = "\n".join(lines) + "\n"
    path = Path("docs/api-coverage.md")
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("API coverage is stale")
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
